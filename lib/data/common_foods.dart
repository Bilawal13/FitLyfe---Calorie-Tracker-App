/// Smart search function for common foods with query normalization & scoring.
List<Meal> searchCommonFoods(String query) {
  final cleanQuery = query.trim().toLowerCase();
  if (cleanQuery.isEmpty) return [];

  final tokens = cleanQuery.split(RegExp(r'\s+')).where((t) => t.isNotEmpty).toList();

  final List<MapEntry<CommonFoodItem, int>> scored = [];

  for (final item in commonFoodsDatabase) {
    final lowerName = item.name.toLowerCase();
    int score = 0;

    // Exact name match
    if (lowerName == cleanQuery) {
      score += 100;
    } else if (lowerName.startsWith(cleanQuery)) {
      score += 60;
    } else if (lowerName.contains(cleanQuery)) {
      score += 40;
    }

    // Keyword match
    for (final kw in item.keywords) {
      final lowerKw = kw.toLowerCase();
      if (lowerKw == cleanQuery) {
        score += 80;
      } else if (lowerKw.startsWith(cleanQuery)) {
        score += 50;
      } else if (lowerKw.contains(cleanQuery)) {
        score += 30;
      }
    }

    // Token-based matching (e.g. "boiled" and "chickpeas")
    int tokenMatches = 0;
    for (final token in tokens) {
      if (lowerName.contains(token) || item.keywords.any((k) => k.contains(token))) {
        tokenMatches++;
      }
    }

    if (tokenMatches == tokens.length) {
      score += 40;
    } else if (tokenMatches > 0) {
      score += (tokenMatches * 15);
    }

    if (score > 0) {
      scored.add(MapEntry(item, score));
    }
  }

  // Sort by highest score first
  scored.sort((a, b) => b.value.compareTo(a.value));

  return scored.map((e) => e.key.toMeal()).toList();
}
