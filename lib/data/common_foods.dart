import '../models/meal.dart';

class CommonFoodItem {
  final String name;
  final String category;
  final double calories;
  final double protein;
  final double carbs;
  final double fat;
  final double fiber;
  final double sodium;
  final List<String> keywords;

  const CommonFoodItem({
    required this.name,
    required this.category,
    required this.calories,
    required this.protein,
    required this.carbs,
    required this.fat,
    required this.fiber,
    required this.sodium,
    this.keywords = const [],
  });

  Meal toMeal() {
    return Meal(
      id: 'common_${name.toLowerCase().replaceAll(RegExp(r'[^a-z0-9]'), '_')}',
      name: name,
      group: category,
      calories: calories,
      protein: protein,
      carbs: carbs,
      fat: fat,
      fiber: fiber,
      sodium: sodium,
    );
  }
}

